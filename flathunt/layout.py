"""Чи можна жити по окремих кімнатах.

Для трикімнатної це головне питання: сенс у ній лише тоді, коли кімнати
ізольовані, а не проходять одна крізь одну. Сигнал збирається з чотирьох
джерел за спаданням надійності.

**Поле OLX.** Сайт віддає «Планування» прямо в параметрах оголошення —
`layout`. Код шукав його під іменами `flat_planning` і `planning`, яких
в OLX немає, тож колонка стояла порожня у всій базі. Насправді поле
заповнене у 69 відсотках трикімнатних.

**Слова в тексті.** «Суміжна», «прохідна», «вагончик».

**Розбір моделлю.** `separate_rooms` вона витягала й раніше, але
результат писався в поле з підкресленням і мовчки губився при збереженні.

**Площа.** Коли не сказано нічого, лишається метраж. На 126 оголошеннях
OLX із відомим плануванням:

    до 55 м²    роздільних 40%,  прохідних 60%
    55-64 м²    роздільних 28%,  прохідних 57%
    65-74 м²    роздільних 88%,  прохідних  3%
    75+  м²     роздільних 79%,  прохідних  4%

Тобто трикімнатна, менша за 65 м², частіше прохідна, ніж ні — це стара
хрущовка. Вище межі ізольованих близько восьми з десяти. Для двокімнатних
такої закономірності немає, тому здогад за площею робиться лише для
трикімнатних і чесно позначається як здогад.
"""

# Значення поля «Планування» в OLX
SEPARATE_WORDS = ("роздільн", "ізольован", "двосторонн")
JOINED_WORDS = ("суміжн", "прохідн", "смежн", "вагончик", "трамвайчик")
# «Вільне планування» — це порожня коробка без стін, а не готові кімнати
OPEN_PLAN = ("вільне планування", "відкрите планування")

YES, NO, MAYBE_NO = "так", "ні", "мабуть ні"

SMALL_THREE_ROOM_M2 = 65


def _text(ad):
    return f"{ad.get('title') or ''} {ad.get('description') or ''}".lower()


def status(ad, cfg=None):
    """«так» / «ні» / «мабуть ні» / None.

    None означає саме незнання, і це не те саме, що «мабуть ні»: у картці
    вони мусять виглядати по-різному, інакше здогад читається як факт.
    """
    rooms = ad.get("rooms") or 0
    if rooms < 2:
        return None

    layout = (ad.get("layout") or "").lower()
    if any(w in layout for w in JOINED_WORDS):
        return NO
    if any(w in layout for w in OPEN_PLAN):
        return NO
    if any(w in layout for w in SEPARATE_WORDS):
        return YES

    text = _text(ad)
    if any(w in text for w in JOINED_WORDS):
        return NO
    if any(w in text for w in SEPARATE_WORDS):
        return YES

    from_model = ad.get("separate_rooms")
    if from_model in (YES, NO):
        return from_model

    # Лишилась тільки площа, і довіряти їй можна лише на трикімнатних
    limit = (cfg or {}).get("layout", {}).get("small_three_room_m2", SMALL_THREE_ROOM_M2)
    area = ad.get("area")
    if rooms >= 3 and area and area < limit:
        return MAYBE_NO
    return None


WORD = {
    YES: "кімнати роздільні",
    NO: "кімнати прохідні — по окремих жити не вийде",
    MAYBE_NO: "площа замала для роздільних — швидше за все прохідні",
}
